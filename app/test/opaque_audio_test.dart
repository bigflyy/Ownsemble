import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:ownsemble/media/audio_cache.dart';
import 'package:ownsemble/media/audio_policy.dart';
import 'package:ownsemble/media/streaming_audio.dart';
import 'package:ownsemble/provider/audio_url_decoder.dart';

/// Cover exact provider audio links whose CDN endpoint has no filename extension.
void main() {
  test('opaque OK CDN sources retain HTTPS and exact host boundaries', () {
    // Represent a signed endpoint without using any real media address.
    final source = Uri.parse('https://generated.okcdn.ru/?fixture=1');
    expect(decodeAudioSource(source.toString(), 0), source);
    expect(selectSource({}, requireBinding: true, boundSource: source), source);
    // Reject lookalike hosts, account authorities, alternate ports and HTTP.
    for (final rejected in [
      'https://generated.okcdn.ru.attacker.test/?fixture=1',
      'https://notokcdn.ru/?fixture=1',
      'http://generated.okcdn.ru/?fixture=1',
      'https://user:secret@generated.okcdn.ru/?fixture=1',
      'https://generated.okcdn.ru:8443/?fixture=1',
    ]) {
      expect(decodeAudioSource(rejected, 0), isNull);
    }
  });

  test('opaque progressive playback starts before the entire response finishes', () async {
    // Isolate complete-cache publication from all existing files.
    final directory = await Directory.systemTemp.createTemp(
      'ownsemble-opaque-progressive-',
    );
    // Hold the response tail until the native relay has already returned bytes.
    final releaseTail = Completer<void>();
    // Serve generated bytes only through a private loopback fixture.
    final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
    server.listen((request) async {
      request.response.contentLength = 128 * 1024;
      request.response.bufferOutput = false;
      request.response.add(List.filled(64 * 1024, 1));
      await request.response.flush();
      await releaseTail.future;
      request.response.add(List.filled(64 * 1024, 2));
      await request.response.close();
    });
    // Keep strict production destinations while allowing only this fixture port.
    final cache = AudioCache(
      directory,
      (_) async => 1,
      fixturePort: server.port,
    );
    // Exercise the same extensionless path as the provider source.
    final stream = StreamingAudio(
      cache,
      Uri.parse('http://127.0.0.1:${server.port}/?fixture=progressive'),
    );
    // Request only a prefix so completion cannot accidentally unblock the test.
    final client = HttpClient()..findProxy = (_) => 'DIRECT';
    try {
      // Open the local player route while the generated response tail is held.
      final local = await stream.open().timeout(const Duration(seconds: 3));
      // Request a small prefix to prove delivery does not depend on EOF.
      final request = await client.getUrl(local);
      request.headers.set(HttpHeaders.rangeHeader, 'bytes=0-31');
      // Bound the response wait so a broken stream fails promptly.
      final response = await request.close().timeout(
        const Duration(seconds: 3),
      );
      expect(
        await response
            .fold<List<int>>([], (bytes, part) => bytes..addAll(part))
            .timeout(const Duration(seconds: 3)),
        List.filled(32, 1),
      );
      expect(stream.downloadComplete, isFalse);
      releaseTail.complete();
      expect((await stream.fetch(stream.source)).length, 128 * 1024);
      expect(cache.networkRequests, 1);
      // Share the downloaded bytes while verifying extensionless offline publication.
      final savedCache = AudioCache(
        directory,
        (_) async => 1,
        fixturePort: server.port,
        resourceLoader: stream.fetch,
      );
      // Publish the same generated recording through complete-cache validation.
      final asset = await savedCache.save(
        const Track('17_1', 'Generated', 'Fixture', 1),
        stream.source,
        recordingEvidence: 'metadata_row',
      );
      expect(asset.entry, endsWith('.mp3'));
      expect(cache.networkRequests, 1);
    } finally {
      // Release the fixture tail even if a bounded startup assertion fails.
      if (!releaseTail.isCompleted) releaseTail.complete();
      client.close(force: true);
      await stream.close(cancel: true);
      await server.close(force: true);
      await directory.delete(recursive: true);
    }
  });

  test('opaque HLS selects the manifest relay and publishes a verified offline asset', () async {
    // Keep generated cache publication separate from the user's catalog.
    final directory = await Directory.systemTemp.createTemp(
      'ownsemble-opaque-',
    );
    // Count manifest transfers separately from generated initialization/segment requests.
    var manifestRequests = 0;
    // Serve a manifest at an extensionless endpoint with generated resource bytes.
    final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
    server.listen((request) async {
      // Return the same bounded manifest for player and cache consumers.
      if (request.uri.path == '/') {
        manifestRequests++;
        request.response.write(
          '#EXTM3U\n#EXT-X-TARGETDURATION:1\n#EXT-X-MAP:URI="init.mp4"\n#EXTINF:1,\npart.ts\n#EXT-X-ENDLIST\n',
        );
      }
      // Return inert initialization/segment bytes to the substituted decoder.
      else {
        request.response.add(List.filled(64, 1));
      }
      await request.response.close();
    });
    // Use the normal cache/relay with only generated decoding substituted.
    final cache = AudioCache(
      directory,
      (_) async => 1,
      fixturePort: server.port,
    );
    // Address the same opaque endpoint from relay and independent cache consumers.
    final source = Uri.parse('http://127.0.0.1:${server.port}/?fixture=hls');
    // Exercise manifest detection without depending on a filename suffix.
    final stream = StreamingAudio(cache, source);
    // Keep local relay requests independent of system proxy settings.
    final client = HttpClient()..findProxy = (_) => 'DIRECT';
    try {
      // Require the relay to choose an HLS route from the manifest prefix.
      final local = await stream.open();
      expect(local.path, endsWith('.m3u8'));
      // Read the generated local manifest instead of contacting any provider.
      final response = await (await client.getUrl(local)).close();
      expect(await utf8.decoder.bind(response).join(), contains('#EXTM3U'));
      // Verify cache format detection independently of streaming URL routing.
      final asset = await cache.save(
        const Track('17_1', 'Generated', 'Fixture', 1),
        source,
        recordingEvidence: 'metadata_row',
      );
      expect(asset.entry, endsWith('.m3u8'));
      await cache.verify(
        asset,
        expectedTrack: const Track('17_1', 'Generated', 'Fixture', 1),
        requireIdentity: true,
      );
      // The relay and independent cache each need one manifest, with no detection refetch.
      expect(manifestRequests, 2);
    } finally {
      client.close(force: true);
      await stream.close(cancel: true);
      await server.close(force: true);
      await directory.delete(recursive: true);
    }
  });
}
